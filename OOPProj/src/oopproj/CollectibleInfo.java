package oopproj;

/**
 *
 * @author mncrf
 */
public class CollectibleInfo {
    
    private String name;
    
    private String location;
    
    public CollectibleInfo(String name, String location) {
        this.name = name;
        this.location = location;
    }
    
    public String getName() {
        return name;
    }
    
   
    
    public String getLocation() {
        return location;
    }
    
   
}
